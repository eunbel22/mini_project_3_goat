# pandas 라이브러리를 불러온다
import pandas as pd

# 환경 확인용 가상 예시 표를 만든다 (상품명은 누가 봐도 가짜, 최저가는 숫자)
df = pd.DataFrame({
    "상품명": ["가짜노트북 테스트A", "가짜노트북 테스트B", "가짜노트북 테스트C"],
    "최저가": [999000, 1050000, 1200000],
})

# 표를 만들기 전에 안내 문구를 출력한다
print("환경 확인용 가상 예시")

# 표 내용을 출력한다
print(df)

# 표의 행/열 크기를 출력한다
print(df.shape)
